CREATE TABLE IF NOT EXISTS scan_job (
 node_id VARCHAR(36) PRIMARY KEY, content_hash VARCHAR(64), source_version VARCHAR(100),
 status VARCHAR(40) NOT NULL, attempts INT NOT NULL DEFAULT 0, updated_at VARCHAR(50),
 analysis CLOB, applied CLOB, error VARCHAR(200), approved_by VARCHAR(150), record_id VARCHAR(36),
 target_folder VARCHAR(36), approved_hash VARCHAR(64), approved_snapshot CLOB
);
CREATE TABLE IF NOT EXISTS scan_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 node_id VARCHAR(36) NOT NULL, event VARCHAR(60) NOT NULL, actor VARCHAR(150),
 at_time VARCHAR(50) NOT NULL, details CLOB
);
CREATE TABLE IF NOT EXISTS separator_check (
 node_id VARCHAR(36) PRIMARY KEY, version_label VARCHAR(100), outcome VARCHAR(40) NOT NULL,
 removed VARCHAR(400), checked_at VARCHAR(50) NOT NULL
);
